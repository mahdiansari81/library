    @Override
    public void run(String... args) {
        if (bookRepository.count() > 0) {
            log.info("دیتابیس از قبل کتاب داره. Skip کردن.");
            return;
        }

        log.info("شروع اضافه کردن ۱۰۰ کتاب...");

        List<Book> books = new ArrayList<>();

        for (int i = 0; i < BOOKS_DATA.length; i++) {
            String name = BOOKS_DATA[i][0];
            String author = BOOKS_DATA[i][1];

            Book book = Book.builder()
                    .bookName(name)
                    .author(author)
                    .bookCode(String.format("978-3-16-148410-%03d", i + 1))
                    .publishYear(1380 + (i % 20))
                    .totalCopies(5)
                    .availableCopies(5)
                    .build();

            books.add(book);
        }

        bookRepository.saveAll(books);
        log.info("✅ {} کتاب با موفقیت اضافه شد!", books.size());
    }
